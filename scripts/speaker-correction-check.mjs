import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, rm, cp } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { tmpdir } from 'node:os';
import { spawn, spawnSync } from 'node:child_process';
import { createInterface } from 'node:readline';
import sherpa from 'sherpa-onnx-node';
import { LocalDiarization } from '../macos/backend/diarization.mjs';
import { cleanSpeakerInterval } from '../macos/backend/service.mjs';
assert.equal(cleanSpeakerInterval([{start:0,end:3,speaker:'Speaker 1'},{start:1,end:2}],0,3),false,'Unknown overlapping voice cannot teach identity');
assert.equal(cleanSpeakerInterval([{start:0,end:3,speaker:'Speaker 1'}],0,3),true);
const models=resolve('.cache/acceleration-models');
await cp(resolve('.cache/speaker-quality/speaker-diarization-accurate'),join(models,'speaker-diarization-accurate'),{recursive:true});
const session=await mkdtemp(join(tmpdir(),'speaker-correction-check-'));
const packaged=process.argv.includes('--packaged'), resources=resolve('release/native/DAVE.app/Contents/Resources');
const child=spawn(packaged?join(resources,'runtime/node'):process.execPath,[packaged?join(resources,'backend/service.mjs'):resolve('macos/backend/service.mjs')],{env:{...process.env,LOCALVOICE_MODELS:models,LOCALVOICE_SESSION:session,LOCALVOICE_WHISPER_BIN:packaged?join(resources,'runtime/whisper-cli'):resolve('.cache/metal-build/build/bin/whisper-cli')},stdio:['pipe','pipe','pipe']});
let next=0,errors='';const pending=new Map();child.stderr.on('data',d=>errors+=d);
createInterface({input:child.stdout}).on('line',line=>{const r=JSON.parse(line),p=pending.get(r.id);if(p){pending.delete(r.id);r.error?p.reject(Error(r.error)):p.resolve(r.result);}});
child.on('exit',()=>{for(const p of pending.values())p.reject(Error(errors||'Service exited'));});
const request=(command,values={})=>new Promise((resolve,reject)=>{const id=String(++next);pending.set(id,{resolve,reject});child.stdin.write(JSON.stringify({id,command,...values})+'\n');});
const timer=setTimeout(()=>child.kill('SIGKILL'),120000);
try {
 const list=await request('speaker-models');assert.equal(list.length,3);assert(list.some(m=>m.id==='precision'));assert(list.find(m=>m.id==='accurate').installed);
 const wave=sherpa.readWave(resolve('test-results/transcription-two-speakers.wav'));
 const file=join(session,'audio.f32');await writeFile(file,Buffer.from(wave.samples.buffer,wave.samples.byteOffset,wave.samples.byteLength));
 const result=await request('transcribe-chunk',{model:'whisper-tiny',device:'metal',speakerModel:'accurate',separateSpeakers:true,expectedSpeakers:2,path:file,jobID:'correction-real'});
 assert.equal(result.acceleration.provider,'metal');assert.equal(new Set(result.segments.map(s=>s.speaker).filter(Boolean)).size,2);
 const evidence=result.segments.filter(s=>s.speakerEmbedding);assert(evidence.length>=2,'Per-caption voice evidence delivered');
 assert(evidence.every(s=>s.speakerEmbedding.length===256&&s.speakerEmbedding.every(Number.isFinite)));
 const words=result.segments.map(s=>s.text).join(' ').toLowerCase();
 assert.match(words,/south/);assert.match(words,/painting/);
 await assert.rejects(request('diarization-status',{speakerModel:'made-up'}),/supported/);
 const runtime=new LocalDiarization(models,{modelID:'accurate'});
 const vectors=[];
 for(const name of ['speaker1-a','speaker2-a','speaker1-b']) vectors.push(await runtime.embeddingFor(sherpa.readWave(resolve('.cache/transcription-fixtures',name+'.wav')).samples));
 const data=join(session,'voice-evidence.json');await writeFile(data,JSON.stringify(vectors));
 const native=spawnSync(process.execPath,['macos/scripts/transcription-check.mjs'],{env:{...process.env,LOCALVOICE_SPEAKER_EVIDENCE:data},encoding:'utf8',timeout:120000});
 assert.equal(native.status,0,native.stderr+native.stdout);assert.match(native.stdout,/NATIVE_SPEAKER_LEARNING_REAL_OK/);
 console.log('SPEAKER_CORRECTION_REAL_OK '+(packaged?'packaged':'source'));
} finally {clearTimeout(timer);child.kill('SIGTERM');await rm(session,{recursive:true,force:true});}
